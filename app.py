# ----------------------------------------------------------------------------- data / model loading
@st.cache_data(show_spinner="Loading dataset...")
def load_data():
    """Load CSVs; regenerate them (same seed) if they are missing, e.g. on a fresh cloud deployment."""
    if not (DATA_PATH.exists() and TOWER_PATH.exists()):
        towers = generate_towers(seed=42)
        df = generate_network_dataset(towers=towers, seed=42)
        DATA_PATH.parent.mkdir(exist_ok=True)
        try:
            towers.to_csv(TOWER_PATH, index=False)
            df.to_csv(DATA_PATH, index=False)
        except OSError:
            pass  # read-only file system: keep in memory only
    else:
        towers, df = pd.read_csv(TOWER_PATH), pd.read_csv(DATA_PATH)
    validate_dataset(df)
    return df, towers


@st.cache_resource(show_spinner="Loading model...")
def load_model(_df):
    """Load the saved model; train (and try to save) a new one if it is missing or incompatible."""
    try:
        return load_bundle(MODEL_PATH)
    except Exception:
        bundle = train_and_evaluate(_df)
        try:
            save_bundle(bundle, MODEL_PATH)
        except OSError:
            pass
        return bundle


df, towers = load_data()
bundle = load_model(df)


@st.cache_data(show_spinner="Computing coverage map...")
def cached_grid(towers_json: str, resolution: int):
    return signal_grid(pd.read_json(StringIO(towers_json)), resolution=resolution)


@st.cache_data(show_spinner="Running optimisation...")
def cached_energy(towers_json: str, load_thr, max_load, tol, min_sig):
    return optimize_energy(pd.read_json(StringIO(towers_json)), load_thr, max_load, tol, min_sig)


@st.cache_data(show_spinner="Running beamforming simulation...")
def cached_beam(towers_json: str, n_el, err, slots):
    return bf.simulate_beamforming(pd.read_json(StringIO(towers_json)), n_elements=n_el, steering_error_deg=err, n_slots=slots)


@st.cache_data(show_spinner="Building comparison...")
def cached_comparison(n_new, n_el, capacity):
    return build_comparison(df, towers, bundle, n_new_towers=n_new, n_elements=n_el, capacity_mbps=capacity)


def tj() -> str:
    return towers.to_json()


