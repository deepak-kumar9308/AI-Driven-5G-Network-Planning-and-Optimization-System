    counts = comp["Result"].value_counts()
    k = st.columns(3)
    k[0].metric("Improved", int(counts.get("Improved", 0)))
    k[1].metric("Worse", int(counts.get("Worse", 0)))
    k[2].metric("Neutral / unchanged", int(counts.get("Neutral / context", 0) + counts.get("No change", 0)))
