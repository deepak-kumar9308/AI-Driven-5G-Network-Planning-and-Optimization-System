def page_slicing():
    st.header("4 · Network Slicing")
    st.caption("eMBB, URLLC and mMTC compete for one cell's capacity. Compare static equal split, dynamic priority allocation and a Q-learning agent.")
    cap = st.slider("Total cell capacity (Mbps)", 400, 2000, 1000, 100)
    demand = ns.hourly_demand(cap)
    static, dyn = ns.simulate_day(demand, cap, "static"), ns.simulate_day(demand, cap, "dynamic")
    s0, s1 = ns.policy_summary(static, cap), ns.policy_summary(dyn, cap)
    k = st.columns(4)
    k[0].metric("Capacity utilisation", f"{s1['capacity_utilization_pct']:.1f} %", f"{s1['capacity_utilization_pct'] - s0['capacity_utilization_pct']:+.1f} pts vs static")
    k[1].metric("Slice SLA satisfaction", f"{s1['sla_satisfaction_pct']:.1f} %", f"{s1['sla_satisfaction_pct'] - s0['sla_satisfaction_pct']:+.1f} pts vs static")
    k[2].metric("Unmet demand", f"{s1['unmet_total_mbps']:.0f} Mbps", f"{s1['unmet_total_mbps'] - s0['unmet_total_mbps']:+.0f} vs static", delta_color="inverse")
    k[3].metric("URLLC SLA met", f"{s1['urllc_sla_pct']:.0f} %")
    hour = st.slider("Inspect hour of day", 0, 23, 20)
    a, b = st.columns(2)
    for col, tbl, name in ((a, static, "Static equal split"), (b, dyn, "Dynamic allocation")):
        h = tbl[tbl["Hour"] == hour].melt(id_vars="Slice", value_vars=["Demand_Mbps", "Allocated_Mbps", "Served_Mbps"], var_name="Quantity")
        col.plotly_chart(viz.bar(h, "Slice", "value", "Quantity", f"{name} - hour {hour:02d}:00"), use_container_width=True)
    daily = pd.concat([static.assign(Policy="Static"), dyn.assign(Policy="Dynamic")])
    st.plotly_chart(viz.line(daily.groupby(["Hour", "Policy"], as_index=False)["Capacity_Utilization_pct"].first(), "Hour",
                             "Capacity_Utilization_pct", "Policy", "Capacity utilisation over the day (%)"), use_container_width=True)
    util = daily.groupby(["Slice", "Policy"], as_index=False)["Slice_Utilization_pct"].mean()
    st.plotly_chart(viz.bar(util, "Slice", "Slice_Utilization_pct", "Policy", "Mean utilisation of allocated resources per slice (%)"), use_container_width=True)
    with st.expander("Slice requirements used"):
        st.dataframe(pd.DataFrame(ns.SLICE_CONFIG).T, use_container_width=True)

    st.subheader("Reinforcement-learning-inspired demo (Q-learning)")
    st.caption("A tabular Q-learning agent learns which capacity split to use for each demand state. It is trained on simulated days when you press the button.")
    episodes = st.slider("Training episodes (simulated days)", 50, 800, 300, 50)
    if st.button("Train Q-learning agent"):
        q, hist = ns.train_q_agent(cap, episodes)
        qtab = ns.simulate_day(demand, cap, alloc_fn=ns.q_allocator(q, cap))
        sq = ns.policy_summary(qtab, cap)
        st.plotly_chart(viz.line(pd.DataFrame({"Episode": range(1, len(hist) + 1), "Avg reward": hist}), "Episode", "Avg reward",
                                 title="Training reward per episode"), use_container_width=True)
        st.dataframe(pd.DataFrame({"Static": s0, "Dynamic": s1, "Q-learning": sq}).round(2), use_container_width=True)
        st.caption("Results are measured on the simulated demand profile above. Q-learning is not guaranteed to beat the dynamic heuristic.")


def page_energy():
    st.header("5 · Energy Efficiency Optimization")
    st.caption("Low-traffic towers sleep only if coverage and neighbour capacity allow it.")
    c = st.columns(4)
    load_thr = c[0].slider("Underutilised if load below (%)", 5, 50, 30)
    max_load = c[1].slider("Max neighbour load after offload (%)", 60, 95, 80)
    tol = c[2].slider("Coverage loss tolerance (pts)", 0.0, 5.0, 1.0, 0.5)
    min_sig = c[3].slider("Minimum usable signal (dBm)", -115, -95, int(ENERGY_MIN_SIGNAL_DBM))
    r = cached_energy(tj(), float(load_thr), float(max_load), float(tol), float(min_sig))
    s = r["summary"]
    k = st.columns(4)
    k[0].metric("Power before", f"{s['power_before_kw']:.2f} kW")
    k[1].metric("Power after", f"{s['power_after_kw']:.2f} kW", f"{s['power_after_kw'] - s['power_before_kw']:+.2f} kW", delta_color="inverse")
    k[2].metric("Estimated savings", f"{s['savings_pct']:.1f} %")
    k[3].metric("Coverage before → after", f"{s['coverage_before_pct']:.1f}% → {s['coverage_after_pct']:.1f}%")
    if s["towers_sleeping"] == 0:
        st.warning("No tower can safely enter sleep mode with these settings - the decision log explains why.")
    else:
        st.success(f"{s['towers_sleeping']} tower(s) can sleep: {', '.join(r['sleeping_ids'])}. Highest load after offload: {s['max_load_after_pct']:.0f}%.")
    both = pd.concat([r["before"].assign(Scenario="Before"), r["after"].assign(Scenario="After")])
    a, b = st.columns(2)
    a.plotly_chart(viz.bar(both, "Tower_ID", "Power_kW", "Scenario", "Power per tower (kW)"), use_container_width=True)
    b.plotly_chart(viz.bar(both, "Tower_ID", "Load_pct", "Scenario", "Load per tower (%)"), use_container_width=True)
    xs, ys, grid, _ = signal_grid(towers, resolution=48, active=~towers["Tower_ID"].isin(r["sleeping_ids"]).to_numpy())
    st.plotly_chart(viz.signal_heatmap(xs, ys, grid, towers, "Coverage after sleep mode (x = sleeping tower)", sleeping=r["sleeping_ids"],
                                       threshold=float(min_sig)), use_container_width=True)
    st.subheader("Decision log")
    st.dataframe(r["decisions"], hide_index=True, use_container_width=True)
    st.caption("Power model: P = P_idle + (P_max − P_idle) × load; sleeping towers draw 10% of idle power. Hourly figures in kW ≈ kWh per hour.")


