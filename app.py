def page_compare():
    st.header("Before vs After Comparison")
    st.caption("Baseline vs optimised values, all calculated from the simulations. Not every metric is expected to improve.")
    c = st.columns(3)
    n_new = c[0].slider("New towers (RF planning)", 0, 6, 3)
